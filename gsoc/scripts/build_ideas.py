#!/usr/bin/env python3
"""Build gsoc/ideas.html from the Markdown files in gsoc/ideas/.

Edit the Markdown, then run:  pip install markdown && python gsoc/scripts/build_ideas.py
The deploy workflow runs this before every gsoc deploy.
"""

import html
import pathlib
import re

import markdown

ROOT = pathlib.Path(__file__).resolve().parent.parent
IDEAS = ROOT / "ideas"
CURRENT = "2027"
ARCHIVE = ["2026", "2025"]


def render(path):
    md = markdown.Markdown(extensions=["extra", "toc", "sane_lists"], extension_configs={"toc": {"permalink": False}})
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"^# .*\n", "", text, count=1)  # page supplies its own title
    body = md.convert(text)
    toc = [t for t in md.toc_tokens if t["level"] == 2] if md.toc_tokens and md.toc_tokens[0]["level"] == 2 else [
        c for t in md.toc_tokens for c in t.get("children", []) if c["level"] == 2
    ]
    return body, toc


def page():
    current_html, current_toc = render(IDEAS / f"{CURRENT}.md")
    toc_items = "\n".join(
        f'<li><a href="#{t["id"]}">{html.escape(t["name"])}</a></li>'
        for t in current_toc
    )
    archive = "\n".join(
        f"""
      <details class="year">
        <summary>GSoC {year} ideas</summary>
        <div class="ideas">{render(IDEAS / f"{year}.md")[0]}</div>
      </details>"""
        for year in ARCHIVE
    )
    return TEMPLATE.format(year=CURRENT, toc=toc_items, current=current_html, archive=archive)


